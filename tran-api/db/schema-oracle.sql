CREATE TABLE CUENTAS (
    CUENTA_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLIENTE_ID NUMBER NOT NULL,
    NUMERO_CUENTA VARCHAR2(30) NOT NULL UNIQUE,
    SALDO NUMBER(14,2) DEFAULT 0 NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVA' NOT NULL,
    CONSTRAINT CK_CUENTAS_ESTADO CHECK (ESTADO IN ('ACTIVA','BLOQUEADA','CANCELADA')),
    CONSTRAINT CK_CUENTAS_SALDO CHECK (SALDO >= 0)
);

CREATE TABLE TARJETAS (
    TARJETA_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUENTA_ID NUMBER NOT NULL,
    NUMERO_TARJETA VARCHAR2(20) NOT NULL UNIQUE,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVA' NOT NULL,
    FECHA_VENCIMIENTO DATE,
    CONSTRAINT FK_TARJETAS_CUENTAS FOREIGN KEY (CUENTA_ID) REFERENCES CUENTAS(CUENTA_ID),
    CONSTRAINT CK_TARJETAS_ESTADO CHECK (ESTADO IN ('ACTIVA','BLOQUEADA','VENCIDA','CANCELADA'))
);

CREATE TABLE MOVIMIENTOS (
    MOVIMIENTO_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUENTA_ID NUMBER NOT NULL,
    TIPO VARCHAR2(30) NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'APLICADO' NOT NULL,
    MONTO NUMBER(14,2) NOT NULL,
    SALDO_ANTERIOR NUMBER(14,2) NOT NULL,
    SALDO_POSTERIOR NUMBER(14,2) NOT NULL,
    REFERENCIA VARCHAR2(50) NOT NULL,
    DESCRIPCION VARCHAR2(200),
    MOVIMIENTO_RELACIONADO_ID NUMBER,
    FECHA_OPERACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_MOVIMIENTOS_CUENTAS FOREIGN KEY (CUENTA_ID) REFERENCES CUENTAS(CUENTA_ID),
    CONSTRAINT FK_MOVIMIENTOS_REL FOREIGN KEY (MOVIMIENTO_RELACIONADO_ID) REFERENCES MOVIMIENTOS(MOVIMIENTO_ID),
    CONSTRAINT CK_MOVIMIENTOS_MONTO CHECK (MONTO > 0),
    CONSTRAINT CK_MOVIMIENTOS_ESTADO CHECK (ESTADO IN ('APLICADO','REVERTIDO')),
    CONSTRAINT CK_MOVIMIENTOS_TIPO CHECK (TIPO IN ('RETIRO','DEPOSITO','TRANSFERENCIA_SALIDA','TRANSFERENCIA_ENTRADA','PAGO_TARJETA','REVERSO'))
);
